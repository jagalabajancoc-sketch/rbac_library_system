<?php
/** Restore a backup produced by setup.php into a new isolated database, then remove only that database. */
require_once __DIR__.'/maintenance.php';
$p=null; $name=null;
try {
    $file=$argv[1] ?? '';
    if (!is_file($file) || !is_file($file.'.sha256')) throw new RuntimeException('Pass a backup generated by setup.php, with its .sha256 file.');
    if (!hash_equals(trim(file_get_contents($file.'.sha256')), hash_file('sha256',$file))) throw new RuntimeException('Backup checksum mismatch.');
    $sql=file_get_contents($file);
    // Ignore text inside SQL string literals: book descriptions can contain words such as 'use'.
    $commands=''; $quote=null; $length=strlen($sql);
    for($i=0;$i<$length;$i++) {
        $ch=$sql[$i];
        if($quote!==null) {
            if($ch===chr(92)) { $i++; continue; }
            if($ch===$quote) {
                if($i+1<$length && $sql[$i+1]===$quote) { $i++; continue; }
                $quote=null;
            }
            continue;
        }
        if($ch===chr(39) || $ch===chr(34)) { $quote=$ch; $commands.=' '; }
        else $commands.=$ch;
    }
    // Only database-local dumps from our backup command are accepted. Do not execute arbitrary SQL uploads here.
    if (preg_match('/\b(?:USE\s+[`\w]|(?:CREATE|DROP|ALTER)\s+DATABASE|(?:CREATE|ALTER)\s+USER|GRANT\s|INTO\s+(?:OUTFILE|DUMPFILE)|SOURCE\s)/i',$commands) || preg_match('/`[^`]+`\s*\.\s*`|\b(?:TRIGGER|PROCEDURE|FUNCTION|EVENT)\b/i',$commands)) {
        throw new RuntimeException('This backup contains statements outside an isolated database; manual review is required.');
    }
    $p=maintenance_connection();
    $name='library_test_restore_'.bin2hex(random_bytes(6));
    $p->exec('CREATE DATABASE '.database_identifier($name).' CHARACTER SET utf8mb4');
    run_database_tool([mysql_tool('mysql'),'--host='.DB_HOST,'--port='.DB_PORT,'--user='.DB_USER,'--binary-mode=1',$name],$file);
    $p->exec('USE '.database_identifier($name));
    $tables=$p->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN);
    preg_match_all('/CREATE TABLE\s+`([^`]+)`/i',$sql,$expected);
    if (!$tables || count($tables)!==count(array_unique($expected[1]))) throw new RuntimeException('Restored table count does not match the backup.');
    $rows=0;
    foreach($tables as $table) $rows+=(int)$p->query('SELECT COUNT(*) FROM '.database_identifier($table))->fetchColumn();
    echo 'Restore verified: '.count($tables).' tables, '.$rows." rows read successfully. Original database untouched.\n";
} catch(Throwable $e) { fwrite(STDERR,$e->getMessage().PHP_EOL); $failed=true; }
finally { if($p && $name && preg_match('/^library_test_restore_[a-f0-9]{12}$/D',$name)) $p->exec('DROP DATABASE '.database_identifier($name)); }
exit(empty($failed)?0:1);
